<?php

$a = 20;

// Operator Penugasan
$a += 10; // $a sekarang bernilai 30
echo $a . "<br>";

$a -= 5; // $a sekarang bernilai 25
echo $a . "<br>";

$a *= 3; // $a sekarang bernilai 75
echo $a . "<br>";

$a /= 5; // $a sekarang bernilai 15
echo $a . "<br>";

$a %= 4; // $a sekarang bernilai 3
echo $a . "<br>";

?>